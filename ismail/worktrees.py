"""Dev copies (git worktrees) of ismail: who owns each, how far it is from the project's main, and what to do next,
so a copy is never stale, forgotten or ownerless (skills/ismail/references/worktrees.md has the decision tree).

    python -m ismail.worktrees                          # list: the next action first, then one line per copy
    python -m ismail.worktrees list --fetch             # ... after a git fetch (default off: it says how old it is)
    python -m ismail.worktrees list --unassigned        # only the copies with no owner (a supervisor's check-in)
    python -m ismail.worktrees list --json
    python -m ismail.worktrees new <topic> --owner <name>     # a new copy from origin/main, owner recorded
    python -m ismail.worktrees claim <path> --owner <name>    # record the owner of a copy that exists
    python -m ismail.worktrees sync <path>              # merge origin/main into the copy
    python -m ismail.worktrees done <path>              # remove a merged, clean copy and its local branch
    python -m ismail.worktrees sweep [--dry-run] [--json]     # remove empty folders removed copies left behind

Every dev works in its own copy, so a live set, the phone and the stage keep running from the main checkout. A copy
is made from origin/main as fetched, never from the local main (it may be behind). The owner records live in the
repository's shared git folder (`git rev-parse --git-common-dir`/ismail-worktrees.json): every copy sees the same
file and nothing enters the repository. Records of copies that no longer exist are dropped on `list` and `sweep`.

On Windows `git worktree remove` cannot remove a copy's folder while a program's working folder is inside it: the
files and git's record go, the empty folder stays, and git never lists it again. `done` tries os.rmdir after git and
says HELD when it cannot; `sweep` removes such empty folders later (siblings named <main>-* and folders in
<main>/.claude/worktrees/ that git does not list), only with os.rmdir, so a folder holding anything stays.

Flags on a copy: UNASSIGNED (no owner: claim it), MERGED (its branch is in origin/main: done, remove it), IDLE
(unmerged, last commit older than IDLE_DAYS: it goes back to its owner, or to the person when it has none), BEHIND
(origin/main has commits it lacks: sync it). Nothing here passes --force to git, stashes or deletes a file: `done`
removes only a copy whose work is all in origin/main and that holds nothing git does not track (caches aside).
The age of a commit is measured against $ISMAIL_WORKTREES_NOW (seconds since 1970) when set, for tests."""
import argparse
import datetime
import json
import os
import re
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 'origin/main'
IDLE_DAYS = 3
STORE = 'ismail-worktrees.json'
# ignored files a copy can lose: regenerated by the next run. Anything else ignored (a scratch folder, a model
# cache, renders) is looked at first, like an untracked file.
CACHES = re.compile(r'(^|/)(__pycache__|\.pytest_cache|\.mypy_cache|\.ruff_cache|\.ipynb_checkpoints|[^/]+\.egg-info)'
                    r'/?$|\.py[co]$')


class WorktreeError(Exception):
    """A refusal: the message says why and what to do next."""


def _git(args, cwd, check=True):
    """Run git in cwd; -> stdout (stripped). With check, a failure raises WorktreeError with git's last line."""
    try:
        r = subprocess.run(['git'] + args, cwd=cwd, capture_output=True, text=True, encoding='utf8',
                           errors='replace', timeout=300)
    except FileNotFoundError:
        raise WorktreeError('git is not installed or not on PATH')
    if check and r.returncode:
        msg = (r.stderr or r.stdout or '').strip().splitlines()
        raise WorktreeError(f"git {' '.join(args[:2])} failed: {msg[-1] if msg else f'exit {r.returncode}'}")
    return r.stdout.strip() if check else r


def _ok(args, cwd):
    return _git(args, cwd, check=False).returncode == 0


def _key(path):
    """One spelling per folder: D:/ismail-x, D:\\ismail-x and d:\\ismail-x\\ are the same copy."""
    return os.path.normcase(os.path.realpath(path))


def _now(now=None):
    if now is not None:
        return float(now)
    env = os.environ.get('ISMAIL_WORKTREES_NOW')
    return float(env) if env else time.time()


def _age(seconds):
    if seconds is None:
        return '?'
    if seconds >= 86400:
        return f'{seconds / 86400:.0f}d'
    return f'{seconds / 3600:.0f}h' if seconds >= 3600 else f'{seconds / 60:.0f}m'


# ---- the repository and its copies ----

def common_dir(repo=HERE):
    """The git folder every worktree of this repository shares."""
    d = _git(['rev-parse', '--git-common-dir'], repo)
    return os.path.normpath(os.path.join(repo, d))


def worktrees(repo=HERE):
    """[{path, head, branch or None, missing}] from `git worktree list`; the first is the main checkout."""
    out, cur = [], None
    for ln in _git(['worktree', 'list', '--porcelain'], repo).splitlines() + ['']:
        if ln.startswith('worktree '):
            cur = {'path': ln[9:], 'head': None, 'branch': None, 'missing': False}
        elif cur is None:
            continue
        elif ln.startswith('HEAD '):
            cur['head'] = ln[5:]
        elif ln.startswith('branch '):
            cur['branch'] = ln[7:].removeprefix('refs/heads/')
        elif ln.startswith('prunable') or ln == 'bare':
            cur['missing'] = True
        elif not ln:
            if not os.path.isdir(cur['path']):
                cur['missing'] = True
            out.append(cur)
            cur = None
    return out


def load_owners(repo=HERE):
    try:
        with open(os.path.join(common_dir(repo), STORE), encoding='utf8') as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def save_owners(owners, repo=HERE):
    """Through a temporary file: a full disk never leaves half a record."""
    path = os.path.join(common_dir(repo), STORE)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix='.ismail-worktrees.')
    with os.fdopen(fd, 'w', encoding='utf8') as f:
        json.dump(owners, f, indent=1, sort_keys=True)
    os.replace(tmp, path)


def prune_owners(repo=HERE, all_wt=None, dry_run=False):
    """Drop the owner records of copies that no longer exist; -> (owners kept, [paths of the records dropped])."""
    all_wt = worktrees(repo) if all_wt is None else all_wt
    owners = load_owners(repo)
    live = {_key(w['path']) for w in all_wt if not w['missing']}
    gone = [k for k in owners if k not in live]
    if gone:
        dropped = [owners[k].get('path', k) for k in gone]
        owners = {k: v for k, v in owners.items() if k in live}
        if not dry_run:
            save_owners(owners, repo)
        return owners, dropped
    return owners, []


def leftovers(repo=HERE, all_wt=None):
    """Folders a removed copy may have left: siblings of the main checkout named <main>-*, and the folders in
    <main>/.claude/worktrees/, that git does not list as a copy. -> [{path, entries, copy_like}]: entries is how many
    files and folders it holds (hidden ones too); copy_like says its name is a dev copy's (<main>-wt-*, or under
    .claude/worktrees/), so a non-empty one is worth a look. Links and junctions are never candidates."""
    all_wt = worktrees(repo) if all_wt is None else all_wt
    main = os.path.normpath(all_wt[0]['path'])
    known = {_key(w['path']) for w in all_wt}
    base = os.path.basename(main)
    places = [(os.path.dirname(main), base + '-'), (os.path.join(main, '.claude', 'worktrees'), '')]
    out = []
    for parent, prefix in places:
        try:
            names = sorted(os.listdir(parent))
        except OSError:
            continue
        for name in names:
            if not os.path.normcase(name).startswith(os.path.normcase(prefix)):
                continue
            path = os.path.join(parent, name)
            if (not os.path.isdir(path) or os.path.islink(path) or getattr(os.path, 'isjunction', lambda p: False)(path)
                    or _key(path) in known):
                continue
            try:
                entries = len(os.listdir(path))
            except OSError:
                continue                                 # unreadable: not ours to judge
            copy_like = not prefix or os.path.normcase(name).startswith(os.path.normcase(base + '-wt-'))
            out.append({'path': path.replace('\\', '/'), 'entries': entries, 'copy_like': copy_like})
    return out


def fetch(repo=HERE):
    _git(['fetch', '--quiet', 'origin'], repo)


def last_fetch(repo=HERE):
    """When origin/main was last fetched (FETCH_HEAD's time), or None."""
    try:
        return os.path.getmtime(os.path.join(common_dir(repo), 'FETCH_HEAD'))
    except OSError:
        return None


def _open_prs(repo):
    """-> ({branch: number}, None) or ({}, why the pull requests were not checked)."""
    try:
        r = subprocess.run(['gh', 'pr', 'list', '--state', 'open', '--limit', '200', '--json', 'number,headRefName'],
                           cwd=repo, capture_output=True, text=True, encoding='utf8', timeout=60)
    except FileNotFoundError:
        return {}, 'gh is not installed'
    except subprocess.TimeoutExpired:
        return {}, 'gh did not answer in 60 s'
    if r.returncode:
        msg = (r.stderr or '').strip().splitlines()
        return {}, msg[-1] if msg else f'gh exit {r.returncode}'
    try:
        return {p['headRefName']: p['number'] for p in json.loads(r.stdout or '[]')}, None
    except (ValueError, KeyError, TypeError):
        return {}, 'gh answered something that is not a list of pull requests'


def _status(path, ignored=False):
    """-> porcelain lines: changed tracked files, '?? ' untracked, and with ignored '!! ' ignored entries."""
    args = ['status', '--porcelain'] + (['--ignored'] if ignored else [])
    return [ln for ln in _git(args, path).splitlines() if ln.strip()]


def survey(repo=HERE, now=None, prs=True, prune=False):
    """Everything `list` shows, as data. Copy: path, branch, owner, ahead, behind, merged (its branch is in
    origin/main through a merge), empty (no commits of its own yet), age_s, files (uncommitted + untracked), pr,
    flags. prune drops the owner records of copies that no longer exist."""
    if not _ok(['rev-parse', '--verify', '--quiet', BASE], repo):
        raise WorktreeError(f'this repository has no {BASE}: run python -m ismail.worktrees list --fetch')
    now = _now(now)
    all_wt = worktrees(repo)
    main, copies = all_wt[0], all_wt[1:]
    owners = prune_owners(repo, all_wt)[0] if prune else load_owners(repo)
    first_parent = set(_git(['rev-list', '--first-parent', BASE], repo).split())
    pr_map, pr_why = _open_prs(main['path']) if prs else ({}, 'not asked')
    out = []
    for w in copies:
        rec = owners.get(_key(w['path']), {})
        c = {'path': w['path'], 'branch': w['branch'], 'owner': rec.get('owner'), 'missing': w['missing'],
             'ahead': None, 'behind': None, 'merged': False, 'empty': False, 'age_s': None, 'files': None,
             'pr': pr_map.get(w['branch']) if w['branch'] else None, 'flags': []}
        if not w['missing']:
            behind, ahead = _git(['rev-list', '--left-right', '--count', f"{BASE}...{w['head']}"], repo).split()
            c['ahead'], c['behind'] = int(ahead), int(behind)
            in_base = c['ahead'] == 0
            # in origin/main and not on its own line of commits: merged in (a fresh copy sits on that line)
            c['merged'] = in_base and w['head'] not in first_parent
            c['empty'] = in_base and not c['merged']
            c['age_s'] = max(0.0, now - int(_git(['log', '-1', '--format=%ct', w['head']], repo) or now))
            c['files'] = len(_status(w['path']))
        flags = c['flags']
        if not c['owner']:
            flags.append('UNASSIGNED')
        if c['missing']:
            flags.append('MISSING')
        elif c['merged']:
            flags.append('MERGED')
        else:
            if c['age_s'] is not None and c['age_s'] > IDLE_DAYS * 86400:
                flags.append('IDLE')
            if c['behind']:
                flags.append('BEHIND')
        out.append(c)
    behind = int(_git(['rev-list', '--count', f"{main['head']}..{BASE}"], repo))
    merges = int(_git(['rev-list', '--count', '--merges', '--first-parent', f"{main['head']}..{BASE}"], repo)) \
        if behind else 0
    return {'main': {'path': main['path'], 'branch': main['branch'], 'behind': behind, 'merges_behind': merges},
            'base': BASE, 'fetched': last_fetch(repo), 'now': now, 'copies': out,
            'prs_checked': prs and pr_why is None, 'prs_why': pr_why if prs else None}


# ---- what it says ----

def _n(k, one, many):
    return f'{k} {one if k == 1 else many}'


def next_action(s):
    """The first line: the most urgent thing to do, with the counts of the rest."""
    cs = s['copies']
    groups = [
        ('MERGED', lambda k, c: f"{_n(k, 'copy', 'copies')} to remove: python -m ismail.worktrees done "
                                f"{c['path'] if k == 1 else '<path>'}"),
        ('MISSING', lambda k, c: f"{_n(k, 'copy has', 'copies have')} no folder: git worktree prune forgets "
                                 "them (it removes no files)"),
        ('UNASSIGNED', lambda k, c: f"{_n(k, 'copy has', 'copies have')} no owner: python -m ismail.worktrees "
                                    f"claim {c['path'] if k == 1 else '<path>'} --owner <name>"),
        ('IDLE', lambda k, c: f"{_n(k, 'copy', 'copies')} idle over {IDLE_DAYS} days: "
                              "ask the owner, or the person when it has none"),
        ('BEHIND', lambda k, c: f"{_n(k, 'copy is', 'copies are')} behind {BASE}: python -m ismail.worktrees sync "
                                f"{c['path'] if k == 1 else '<path>'}"),
    ]
    found = [(flag, [c for c in cs if flag in c['flags']], say) for flag, say in groups]
    found = [(flag, hit, say) for flag, hit, say in found if hit]
    if not found:
        return 'all copies owned and current' if cs else 'no copies: python -m ismail.worktrees new <topic> --owner <name>'
    flag, hit, say = found[0]
    rest = ', '.join(f'{len(h)} {f.lower()}' for f, h, _ in found[1:])
    return say(len(hit), hit[0]) + (f' (also: {rest})' if rest else '')


def main_line(s):
    m = s['main']
    if not m['behind']:
        return None
    return (f"main checkout is {m['behind']} commits behind {BASE} ({m['merges_behind']} merges): {m['path']}; "
            "catch it up only when no live set, phone or stage runs from it")


def fetch_line(s, fetched_now=False):
    if fetched_now:
        return None
    if s['fetched'] is None:
        return f'{BASE} was never fetched here: --fetch to fetch it'
    return f"{BASE} as of the last fetch, {_age(max(0.0, s['now'] - s['fetched']))} ago (--fetch to refresh)"


def copy_line(c, wide=(0, 0)):
    """One copy: path, branch, owner, ahead/behind origin/main, merged, last commit's age, uncommitted + untracked
    files, its open pull request, flags. wide pads the path and branch columns."""
    head = f"  {c['path']:<{wide[0]}}  {c['branch'] or '(detached)':<{wide[1]}}  owner {c['owner'] or '-'}"
    if c['missing']:
        return f"{head}  folder missing  {' '.join(c['flags'])}"
    state = 'merged' if c['merged'] else 'no commits yet' if c['empty'] else 'unmerged'
    pr = f"  PR #{c['pr']}" if c['pr'] else ''
    return (f"{head}  +{c['ahead']}/-{c['behind']}  {state}  last commit {_age(c['age_s'])} ago  "
            f"{_n(c['files'], 'file', 'files')}{pr}  {' '.join(c['flags'])}").rstrip()


def report(s, unassigned=False, flagged=False, fetched_now=False):
    """-> lines: the next action, the main checkout, how fresh origin/main is, then the copies."""
    lines = [next_action(s)]
    lines += [x for x in (main_line(s), fetch_line(s, fetched_now)) if x]
    cs = [c for c in s['copies'] if (not unassigned or not c['owner']) and (not flagged or c['flags'])]
    wide = (max((len(c['path']) for c in cs), default=0), max((len(c['branch'] or '(detached)') for c in cs), default=0))
    lines += [copy_line(c, wide) for c in cs]
    if s['prs_why'] and s['prs_why'] != 'not asked':
        lines.append(f"pull requests were not checked ({s['prs_why']})")
    return lines


def intake_lines(repo=HERE):
    """For `python -m ismail.handoffs`: the next action, the main checkout, and the flagged copies only."""
    s = survey(repo, prs=False)
    lines = report(s, flagged=True)
    empty = [f for f in leftovers(repo) if not f['entries']]
    if empty:
        lines.append(f"{_n(len(empty), 'empty leftover folder', 'empty leftover folders')} next to the main checkout: "
                     "python -m ismail.worktrees sweep")
    return lines


# ---- the commands that change something ----

def _find(path, repo):
    """The worktree record for a path, or a refusal that lists the copies."""
    all_wt = worktrees(repo)
    for i, w in enumerate(all_wt):
        if _key(w['path']) == _key(path):
            return w, i == 0
    raise WorktreeError(f"{path} is not a copy of this repository; python -m ismail.worktrees lists them")


def _copy(path, repo, what):
    w, is_main = _find(path, repo)
    if is_main:
        raise WorktreeError(f"{w['path']} is the main checkout, not a copy: it is shared and has no owner, and it is "
                            f"caught up only when no live set, phone or stage runs from it (worktrees.md). {what}")
    return w


def new(topic, owner, repo=HERE):
    """A new copy on a new branch <topic> from origin/main, next to the main checkout; -> what was made."""
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]*', topic) or not _ok(['check-ref-format', '--branch', topic], repo):
        raise WorktreeError(f"'{topic}' is not a usable topic: letters, digits, '.', '_' and '-' only, e.g. live-fades")
    if not owner.strip():
        raise WorktreeError('say who owns it: --owner <name>')
    all_wt = worktrees(repo)
    main = all_wt[0]['path']
    folder = os.path.join(os.path.dirname(os.path.normpath(main)),
                          f'{os.path.basename(os.path.normpath(main))}-wt-{topic}').replace('\\', '/')
    for k, rec in load_owners(repo).items():
        if topic in (rec.get('topic'), rec.get('branch')) and k in {_key(w['path']) for w in all_wt}:
            raise WorktreeError(f"{rec.get('owner')} already has the topic {topic} ({rec.get('path', k)}): ask them, or "
                                "the person, before starting a second copy on it; never two copies on one topic")
    if os.path.exists(folder):
        raise WorktreeError(f'{folder} already exists: pick another topic, or if it is your copy, record yourself: '
                            f'python -m ismail.worktrees claim {folder} --owner {owner}')
    if _ok(['show-ref', '--verify', '--quiet', f'refs/heads/{topic}'], repo):
        where = [w['path'] for w in all_wt if w['branch'] == topic]
        raise WorktreeError(f"a branch {topic} already exists{f' in {where[0]}' if where else ' (no copy has it)'}: "
                            'pick another topic, or ask its owner or the person about that branch')
    try:
        fetch(repo)
    except WorktreeError as e:
        raise WorktreeError(f'{e}; a copy starts from {BASE} as fetched, so fetch first (the network, or the '
                            'remote), then run this again')
    if _ok(['show-ref', '--verify', '--quiet', f'refs/remotes/origin/{topic}'], repo):
        raise WorktreeError(f'origin already has a branch {topic} (someone\'s pull request?): pick another topic')
    _git(['worktree', 'add', '--quiet', '--no-track', '-b', topic, folder, BASE], repo)
    owners = load_owners(repo)
    owners[_key(folder)] = {'owner': owner, 'topic': topic, 'branch': topic, 'path': folder,
                            'since': datetime.datetime.now().astimezone().isoformat(timespec='seconds')}
    save_owners(owners, repo)
    head = _git(['log', '-1', '--format=%h %s', BASE], repo)
    return (f'made {folder} on a new branch {topic} from {BASE} ({head}), owner {owner}. Work and run the tests '
            f'there; when its pull request is merged: python -m ismail.worktrees done {folder}')


def claim(path, owner, repo=HERE, reassign=False):
    w = _copy(path, repo, 'Nothing to claim.')
    if not owner.strip():
        raise WorktreeError('say who owns it: --owner <name>')
    owners = load_owners(repo)
    k = _key(w['path'])
    had = owners.get(k, {}).get('owner')
    if had and had != owner and not reassign:
        raise WorktreeError(f"{w['path']} is owned by {had}: ask them or the person; to hand it over, run this again "
                            'with --reassign')
    owners[k] = {**owners.get(k, {}), 'owner': owner, 'branch': w['branch'], 'path': w['path'],
                 'topic': owners.get(k, {}).get('topic') or w['branch'],
                 'since': datetime.datetime.now().astimezone().isoformat(timespec='seconds')}
    save_owners(owners, repo)
    return f"{w['path']} ({w['branch'] or 'detached'}) is owned by {owner}" + (f' (was {had})' if had and had != owner
                                                                               else '')


def sync(path, repo=HERE):
    """Merge origin/main into a copy; -> (exit code, message). Conflicts stay in progress for the copy's owner."""
    w = _copy(path, repo, 'Nothing to sync.')
    p = w['path']
    if w['missing']:
        raise WorktreeError(f'{p} has no folder any more: git worktree prune forgets it (it removes no files)')
    if not w['branch']:
        raise WorktreeError(f'{p} is on a detached commit, not a branch: make a branch there first '
                            f'(git -C {p} switch -c <topic>), then sync')
    if _ok(['rev-parse', '--verify', '--quiet', 'MERGE_HEAD'], p):
        raise WorktreeError(f'{p} has a merge in progress: resolve each conflicted file (git -C {p} diff '
                            '--name-only --diff-filter=U), git add them and commit, then sync again')
    changed = [ln for ln in _status(p) if not ln.startswith('??')]
    if changed:
        raise WorktreeError(f'{p} has {len(changed)} uncommitted changes: commit them on {w["branch"]} first, then '
                            'sync. Never stash: the stash stack is shared by every copy')
    try:
        fetch(repo)
    except WorktreeError as e:
        raise WorktreeError(f'{e}; sync merges {BASE} as fetched, so fetch first, then run this again')
    behind = int(_git(['rev-list', '--count', f'HEAD..{BASE}'], p))
    if not behind:
        return 0, f'{p} ({w["branch"]}) already has everything in {BASE}'
    r = _git(['merge', '--no-edit', BASE], p, check=False)
    if r.returncode == 0:
        return 0, (f'merged {BASE} ({behind} commits) into {w["branch"]} in {p}, no conflicts; run the tests your '
                   'change touches before pushing')
    conflicted = _git(['diff', '--name-only', '--diff-filter=U'], p).splitlines()
    if not conflicted:
        msg = (r.stderr or r.stdout or '').strip().splitlines()
        return 1, (f"the merge did not start: {msg[-1] if msg else 'git merge failed'}. Nothing changed in {p}; if git "
                   'names untracked files it would overwrite, move them out of the way (never delete), then sync again')
    lines = [f'merging {BASE} into {w["branch"]} in {p}: {len(conflicted)} conflicted files, the merge is kept in '
             'progress for you to finish:']
    lines += [f'  {f}' for f in conflicted]
    lines.append('Resolve each one, then explain each conflict to the person in their own terms: what both sides '
                 'wanted and what you kept. CHANGELOG.md conflicts usually keep both sides. Then git add the files and '
                 f'git -C {p} commit --no-edit.')
    return 1, '\n'.join(lines)


HELD = "a program's working folder is inside it (often a shell that cd'd there): leave it, the next sweep removes it"


def _remove_empty(p):
    """After git removed a copy: its folder, if still there and empty, goes with os.rmdir (never recursive: rmdir
    refusing a folder that holds anything is the safety net). -> '' or what is left and why."""
    if not os.path.isdir(p):
        return ''
    try:
        if os.listdir(p):
            return f'; its folder {p} still holds files git left: look at them (move what matters with `python -m ismail.reclaim move <path> <what>`: _reclaim/ at the drive root)'
        os.rmdir(p)
        return ''
    except OSError:
        return f'; its empty folder is HELD: {HELD}'


def sweep(repo=HERE, dry_run=False):
    """Remove the empty folders removed copies left behind, and drop the owner records of copies that no longer
    exist. -> {folders: [{path, action: removed|held|left, why}], records_dropped, dry_run}. Only os.rmdir is used:
    a folder that holds anything is never removed, and one with a name like a copy's is listed for a look."""
    all_wt = worktrees(repo)
    folders = []
    for f in leftovers(repo, all_wt):
        p = f['path']
        if f['entries']:
            if f['copy_like']:
                n = _n(f['entries'], 'entry', 'entries')
                folders.append({'path': p, 'action': 'left', 'why': f'not a dev copy, left alone ({n}; git does '
                                'not list it): look at it, or ask the person'})
            continue
        if dry_run:
            folders.append({'path': p, 'action': 'removed', 'why': 'empty, not a copy'})
            continue
        try:
            os.rmdir(p)
            folders.append({'path': p, 'action': 'removed', 'why': 'empty, not a copy'})
        except OSError:
            folders.append({'path': p, 'action': 'held', 'why': HELD})
    dropped = prune_owners(repo, all_wt, dry_run=dry_run)[1]
    return {'folders': folders, 'records_dropped': dropped, 'dry_run': dry_run}


def sweep_lines(res):
    """-> one line per folder, then the count line."""
    dry = res['dry_run']
    say = {'removed': 'would remove' if dry else 'removed', 'held': 'HELD', 'left': 'left alone'}
    lines = [f"  {say[f['action']]}  {f['path']}: {f['why']}" for f in res['folders']]
    lines += [f"  {'would drop' if dry else 'dropped'} the owner record of {p} (its copy no longer exists)"
              for p in res['records_dropped']]
    count = {a: sum(f['action'] == a for f in res['folders']) for a in say}
    parts = [f"{count['removed']} {'would be removed' if dry else 'removed'}"]
    parts += [f"{count['held']} held", f"{count['left']} left alone"] if not dry else [f"{count['left']} left alone"]
    parts.append(_n(len(res['records_dropped']), 'owner record', 'owner records') +
                 (' would be dropped' if dry else ' dropped'))
    lines.append(('dry run, nothing changed: ' if dry else 'swept: ') + ', '.join(parts))
    return lines


def done(path, repo=HERE):
    """Remove a copy whose work is all in origin/main and that holds nothing untracked; -> what was removed."""
    w = _copy(path, repo, 'Nothing to remove.')
    p = w['path']
    if w['missing']:
        raise WorktreeError(f'{p} has no folder any more: git worktree prune forgets it (it removes no files)')
    if _key(os.getcwd()) == _key(p) or _key(os.getcwd()).startswith(_key(p) + os.sep):
        raise WorktreeError(f'this command runs inside {p}: run it from another folder (the main checkout)')
    try:
        fetch(repo)
        stale = ''
    except WorktreeError as e:
        stale = f' ({BASE} could not be fetched, so it may be old: {e})'
    if not _ok(['merge-base', '--is-ancestor', w['head'], BASE], repo):
        ahead = _git(['rev-list', '--count', f"{BASE}..{w['head']}"], repo)
        raise WorktreeError(f"{p} ({w['branch'] or 'detached'}) is not merged: {ahead} commits are not in {BASE}"
                            f"{stale}; open or finish its pull request, or ask the person before dropping it")
    st = _status(p, ignored=True)
    changed = [ln[3:] for ln in st if not ln.startswith(('??', '!!'))]
    if changed:
        raise WorktreeError(f"{p} has {len(changed)} uncommitted changes ({', '.join(changed[:5])}"
                            f"{', ...' if len(changed) > 5 else ''}): they are someone's work. Commit them on a branch "
                            'and open a pull request, or ask its owner or the person')
    loose = [ln[3:] for ln in st if ln.startswith('??') or (ln.startswith('!!') and not CACHES.search(ln[3:]))]
    if loose:
        raise WorktreeError(f"{p} holds {len(loose)} files git does not track ({', '.join(loose[:5])}"
                            f"{', ...' if len(loose) > 5 else ''}): look at them; move what matters with "
                            '`python -m ismail.reclaim move <path> <what>` (_reclaim/ at the root of the drive), never '
                            'delete. Then run done again')
    main = worktrees(repo)[0]['path']
    r = _git(['worktree', 'remove', p], main, check=False)
    if r.returncode and _key(p) in {_key(x['path']) for x in worktrees(repo)}:
        msg = (r.stderr or r.stdout or '').strip().splitlines()
        raise WorktreeError(f"git worktree remove failed: {msg[-1] if msg else f'exit {r.returncode}'}")
    # on Windows git removes the files and the record but not a folder some program's working folder is inside
    left = _remove_empty(p)
    said = f'removed {p}'
    if w['branch']:
        if not _ok(['branch', '--quiet', '-d', w['branch']], main):
            # -d compares with the main checkout's HEAD, which may be behind: the branch is in origin/main (checked
            # above), so delete the ref only if it still points where it did
            _git(['update-ref', '-d', f"refs/heads/{w['branch']}", w['head']], main)
            _git(['config', '--remove-section', f"branch.{w['branch']}"], main, check=False)
        said += f" and its local branch {w['branch']} (its work is in {BASE})"
    owners = load_owners(repo)
    if owners.pop(_key(p), None) is not None:
        save_owners(owners, repo)
    return said + stale + left


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    sub = ap.add_subparsers(dest='cmd')
    ls = sub.add_parser('list', help='the next action, then one line per copy (the default)')
    for p in (ap, ls):
        p.add_argument('--fetch', action='store_true', help='git fetch first (default off: it says how old the data is)')
        p.add_argument('--json', action='store_true')
        p.add_argument('--unassigned', action='store_true', help='only the copies with no owner')
    n = sub.add_parser('new', help='a new copy from origin/main: new <topic> --owner <name>')
    n.add_argument('topic')
    n.add_argument('--owner', required=True)
    c = sub.add_parser('claim', help='record the owner of a copy that exists: claim <path> --owner <name>')
    c.add_argument('path')
    c.add_argument('--owner', required=True)
    c.add_argument('--reassign', action='store_true', help='hand a copy that has an owner to another')
    s = sub.add_parser('sync', help='merge origin/main into a copy: sync <path>')
    s.add_argument('path')
    d = sub.add_parser('done', help='remove a merged, clean copy and its local branch: done <path>')
    d.add_argument('path')
    w = sub.add_parser('sweep', help='remove the empty folders removed copies left, drop stale owner records')
    w.add_argument('--dry-run', action='store_true', help='list what it would remove; change nothing')
    w.add_argument('--json', action='store_true')
    ap.add_argument('--repo', default=HERE, help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(errors='replace')
    if a.cmd in (None, 'list'):
        try:
            if a.fetch:
                fetch(a.repo)
            data = survey(a.repo, prune=True)
        except WorktreeError as e:
            print(f'worktrees: could not look ({e})')
            return 0                                 # a report: it never fails a caller's script
        print(json.dumps(data, indent=1) if a.json else '\n'.join(report(data, a.unassigned, fetched_now=a.fetch)))
        return 0
    try:
        if a.cmd == 'new':
            print(new(a.topic, a.owner, a.repo))
        elif a.cmd == 'claim':
            print(claim(a.path, a.owner, a.repo, a.reassign))
        elif a.cmd == 'sync':
            code, msg = sync(a.path, a.repo)
            print(msg)
            return code
        elif a.cmd == 'done':
            print(done(a.path, a.repo))
        elif a.cmd == 'sweep':
            res = sweep(a.repo, a.dry_run)
            print(json.dumps(res, indent=1) if a.json else '\n'.join(sweep_lines(res)))
    except WorktreeError as e:
        print(f'refused: {e}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
